const FRAGMENT_CSS = `
[data-marp-preview-fragment-hidden],
[data-marp-preview-fragment-hidden] * {
  visibility: hidden !important;
}
`.trim();

function cloneToken(token) {
  const cloned = Object.assign(
    Object.create(Object.getPrototypeOf(token)),
    token,
  );
  if (token.attrs) cloned.attrs = token.attrs.map((attr) => [...attr]);
  if (token.children) cloned.children = token.children.map(cloneToken);
  if (token.meta) cloned.meta = { ...token.meta };
  if (token.map) cloned.map = [...token.map];
  return cloned;
}

function visitTokens(tokens, visitor) {
  for (const token of tokens) {
    visitor(token);
    if (token.children) visitTokens(token.children, visitor);
  }
}

function removeAttribute(token, name) {
  if (token.attrs) token.attrs = token.attrs.filter(([key]) => key !== name);
}

function expandFragments(state) {
  if (state.inlineMode) return;

  const reservedIds = new Set();
  let nextFootnoteId = 0;
  visitTokens(state.tokens, (token) => {
    const id = token.attrGet('id');
    if (id) reservedIds.add(id);
    if (
      token.type.startsWith('footnote_') &&
      typeof token.meta?.id === 'number'
    ) {
      nextFootnoteId = Math.max(nextFootnoteId, token.meta.id + 1);
    }
  });

  function makeId(id, step) {
    const base = `${id}-fragment-${step}`;
    let candidate = base;
    let suffix = 1;
    while (reservedIds.has(candidate)) candidate = `${base}-${suffix++}`;
    reservedIds.add(candidate);
    return candidate;
  }

  const expanded = [];
  for (let index = 0; index < state.tokens.length; index += 1) {
    const token = state.tokens[index];
    if (token.meta?.marpitSlideElement !== 1) {
      expanded.push(token);
      continue;
    }

    const start = index;
    while (state.tokens[index].meta?.marpitSlideElement !== -1) index += 1;
    const slide = state.tokens.slice(start, index + 1);
    const section = slide.find((item) => item.type === 'marpit_slide_open');
    const count = Number(section?.attrGet('data-marpit-fragments')) || 0;
    if (count === 0) {
      expanded.push(...slide);
      continue;
    }

    for (let step = 0; step <= count; step += 1) {
      const tokens = slide.map(cloneToken);
      tokens[0].attrSet('data-marp-preview-fragment-step', step);
      const ids = new Map();
      const footnoteIds = new Map();
      visitTokens(tokens, (item) => {
        // Flatten the fragments so presentation templates cannot reveal them
        // a second time. Visibility keeps the layout identical in every copy.
        const fragment = Number(item.attrGet('data-marpit-fragment'));
        removeAttribute(item, 'data-marpit-fragments');
        removeAttribute(item, 'data-marpit-fragment');
        if (fragment > step) {
          item.attrSet('data-marp-preview-fragment-hidden', '');
          item.attrSet('aria-hidden', 'true');
        }

        if (step > 0) {
          const id = item.attrGet('id');
          if (id) {
            if (!ids.has(id)) ids.set(id, makeId(id, step));
            item.attrSet('id', ids.get(id));
          }
          // Footnote IDs are generated by renderer rules, not token attrs.
          if (
            item.type.startsWith('footnote_') &&
            typeof item.meta?.id === 'number'
          ) {
            const originalId = item.meta.id;
            if (!footnoteIds.has(originalId)) {
              footnoteIds.set(originalId, nextFootnoteId++);
            }
            item.meta.id = footnoteIds.get(originalId);
          }
        }
      });
      visitTokens(tokens, (item) => {
        const href = item.attrGet('href');
        if (href?.startsWith('#') && ids.has(href.slice(1))) {
          item.attrSet('href', `#${ids.get(href.slice(1))}`);
        }
      });
      expanded.push(...tokens);
    }
  }

  // Keep the original pagination attrs, while describing the physical deck
  // correctly to subsequent Marpit plugins and the CLI's slide collector.
  const total = expanded.filter(
    (token) => token.meta?.marpitSlideElement === 1,
  ).length;
  let slideIndex = -1;
  for (const token of expanded) {
    if (token.meta?.marpitSlideElement === 1) slideIndex += 1;
    if (typeof token.meta?.marpitSlide === 'number') {
      token.meta.marpitSlide = slideIndex;
      token.meta.marpitSlideTotal = total;
    }
  }
  state.tokens = expanded;
}

function installFragments(marp) {
  // Pagination, scoped styles, backgrounds and margins are already applied.
  // Expand before slide containers wrap each resulting physical slide.
  marp.markdown.core.ruler.after(
    'marpit_header_and_footer',
    'marp_preview_fragments',
    expandFragments,
  );
  const renderStyle = marp.renderStyle.bind(marp);
  marp.renderStyle = (theme) => `${renderStyle(theme)}\n${FRAGMENT_CSS}`;
  return marp;
}

module.exports = { FRAGMENT_CSS, installFragments };
